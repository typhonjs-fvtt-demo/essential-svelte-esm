/**
 * It is best practice to configure and initialize data sources separately from your UI facing components.
 * `ItemContext` automatically configures the reactive `GameSettingArrayObject` stores associated with reactive
 * game settings for both `user` and `world` scope demos and provides a unified context accessible in all Svelte
 * components.
 *
 * `GameSettingArrayObject` allows serializing a bespoke array of objects to the Foundry DB through a game setting that
 * fulfills a purpose in your app. This can be specialized data driving your app. There are two scoping options. The
 * first is `user` scope which creates a unique object array per user that is only readable / writable by that user.
 * The second is `world` scope which is only editable by GM users, but is readable by all.
 *
 * Furthermore, `GameSettingArrayObject` is a `CrudArrayObjectStore` allowing the creation of a reactive entry store
 * per object. You must define this store implementation to match the object data being saved. Internally all entry
 * objects are synchronized across clients. In this demo the entry store is {@link ItemEntryStore} defined below.
 * Another features of `CrudArrayObjectStore` is a built-in `DynArrayReducer` which allows non-destructive filtering /
 * sorting of the data contained. This is very handy for creating dynamic table displays of the data or other ordering
 * mechanisms of data driven UI components.
 *
 * This demo creates an array object store with a trivial demo of fake items with a name and category generated by
 * {@link ItemGenerator}.
 *
 * @example
 * ```js
 * const { canEdit } = getContext('#external').itemContext;
 * ```
 *
 * @see https://typhonjs-fvtt-lib.github.io/api-docs/classes/_runtime_svelte_store_reducer_array-object.CrudArrayObjectStore.html
 * @see https://typhonjs-fvtt-lib.github.io/api-docs/classes/_runtime_svelte_store_reducer.DynArrayReducer.html
 */

/**
 * Defines the `itemContext` instance set as `#external` data to all Svelte components.
 */
export class ItemContext
{
   /**
    * Provides the item entry stores.
    *
    * @type {({
    *    user?: ItemArrayObjectStore,
    *    world?: ItemArrayObjectStore
    * })}
    */
   static #itemStores = {};

   /**
    * @type {WeakRef<import('#runtime/svelte/application').SvelteApp>}
    */
   #application;

   #data;

   constructor(application)
   {
      ItemContext.#initialize();

      const scope = application?.options?.settingScope;

      if (scope !== 'user' && scope !== 'world') { throw new Error(`'settingScope' must be 'user' or 'world'.`); }

      this.#application = new WeakRef(application);

      this.#data = {
         ItemGenerator,
         itemStore: ItemContext.#itemStores[scope],
         layoutType:
          application.reactive.sessionStorage.getStore(`${sessionConstants.arrayObjectLayout}${scope}`, 'grid'),
         layoutTypeKey: `${sessionConstants.arrayObjectLayout}${scope}`,
         maxItems: 25,
         menuItems: new MenuItems(this),
         scope,
         scrollTop: application.reactive.sessionStorage.getStore(`${sessionConstants.arrayObjectScrolltop}${scope}`, 0),
      };
   }

   /**
    * @returns {typeof ItemGenerator} Item generator instance.
    */
   get ItemGenerator()
   {
      return this.#data.ItemGenerator;
   }

   /**
    * @returns {ItemArrayObjectStore} The scoped item store.
    */
   get itemStore()
   {
      return this.#data.itemStore;
   }

   /**
    * @returns {import('svelte/store').Writable<string>} Item entries layout type; 'grid' or 'table'.
    */
   get layoutType()
   {
      return this.#data.layoutType;
   }

   /**
    * @returns {string} Session storage key for `layoutType`; used in `MenuItems`.
    */
   get layoutTypeKey()
   {
      return this.#data.layoutTypeKey;
   }

   /**
    * @returns {number} The max allowed number of items to create.
    */
   get maxItems()
   {
      return this.#data.maxItems;
   }

   /**
    * @returns {MenuItems} Menu item data generator.
    */
   get menuItems()
   {
      return this.#data.menuItems;
   }

   /**
    * @returns {string} The current scope; `user` or `world`.
    */
   get scope()
   {
      return this.#data.scope;
   }

   /**
    * @returns {import('svelte/store').Writable<number>} Session storage store for `TJSScrollContainer`.
    */
   get scrollTop()
   {
      return this.#data.scrollTop;
   }

   // Package scope --------------------------------------------------------------------------------------------------

   /**
    * @package
    *
    * @returns {import('#runtime/svelte/application').SvelteApp | undefined} SvelteApp reference.
    */
   get application()
   {
      return this.#application.deref();
   }

   // Internal Implementation ----------------------------------------------------------------------------------------

   static #initialize()
   {
      if (ItemContext.#itemStores.user !== void 0) { return; }

      ItemContext.#itemStores.user = new ItemArrayObjectStore({
         key: settings.userItemsArray,
         scope: 'user'
      });

      ItemContext.#itemStores.world = new ItemArrayObjectStore({
         key: settings.worldItemsArray,
         scope: 'world'
      });
   }
}

