import { GameSettingArrayObject }   from '#runtime/svelte/store/fvtt/settings/array-object';
import { DynReducerHelper }         from '#runtime/svelte/store/reducer';

import { MenuItems }                from './MenuItems.js';
import { ItemGenerator }            from './ItemGenerator.js';

import { constants, settings }      from "#constants";
import { gameSettings }             from '#gameSettings';

/**
 * It is best practice to configure and initialize data sources separately from your UI facing components.
 * `ItemConfiguration` automatically configures the reactive `GameSettingArrayObject` stores associated with reactive
 * game settings for both `user` and `world` scope demos using the Foundry `ready` hook. Additionally, a context for all
 * data utilized in the demo is created in {@link ItemConfiguration.getContext}.
 *
 * `GameSettingArrayObject` allows serializing a bespoke array of objects to the Foundry DB through a game setting that
 * fulfills a purpose in your app. This can be specialized data driving your app. There are two scoping options. The
 * first is `user` scope which creates a unique object array per user that is only readable / writable by that user.
 * The second is `world` scope which is only editable by GM users, but is readable by all.
 *
 * Furthermore, `GameSettingArrayObject` is a `CrudArrayObjectStore` allowing the creation of a reactive entry store
 * per object. You must define this store implementation to match the object data being saved. Internally all entry
 * objects are synchronized across clients. In this demo the entry store is {@link ItemEntryStore} defined below.
 * Another features of `CrudArrayObjectStore` is a built-in `DynArrayReducer` which allows non-destructive filtering /
 * sorting of the data contained. This is very handy for creating dynamic table displays of the data or other ordering
 * mechanisms of data driven UI components.
 *
 * This demo creates an array object store with a trivial demo of fake items with a name and category generated by
 * {@link ItemGenerator}.
 *
 * @see https://typhonjs-fvtt-lib.github.io/api-docs/classes/_runtime_svelte_store_reducer_array-object.CrudArrayObjectStore.html
 * @see https://typhonjs-fvtt-lib.github.io/api-docs/classes/_runtime_svelte_store_reducer.DynArrayReducer.html
 */
export class ItemConfiguration
{
   /**
    * Provides the item entry stores.
    *
    * @type {({
    *    user?: GameSettingArrayObject<ItemEntryStore>,
    *    world?: GameSettingArrayObject<ItemEntryStore>
    * })}
    */
   static #itemStores = {};

   /**
    * Provides search filters for both `name` and `category` properties.
    *
    * @type {({
    *    user: DynReducerHelper.FilterFn.regexObjectQuery,
    *    world: DynReducerHelper.FilterFn.regexObjectQuery
    * })}
    */
   static #searchFilters =
   {
      user: DynReducerHelper.filters.regexObjectQuery(['name', 'category']),
      world: DynReducerHelper.filters.regexObjectQuery(['name', 'category'])
   };

   static initialize()
   {
      if (ItemConfiguration.#itemStores.user !== void 0) { return; }

      ItemConfiguration.#itemStores.user = new GameSettingArrayObject({
         gameSettings,
         namespace: constants.moduleId,
         key: settings.userItemsArray,
         scope: 'user',
         StoreClass: ItemEntryStore,
         dataReducer: true
      });

      // @ts-expect-error - This is OK despite type differences.
      ItemConfiguration.#itemStores.user.dataReducer.filters.add(ItemConfiguration.#searchFilters.user);

      ItemConfiguration.#itemStores.world = new GameSettingArrayObject({
         gameSettings,
         namespace: constants.moduleId,
         key: settings.worldItemsArray,
         scope: 'world',
         StoreClass: ItemEntryStore,
         dataReducer: true
      });

      // @ts-expect-error - This is OK despite type differences.
      ItemConfiguration.#itemStores.world.dataReducer.filters.add(ItemConfiguration.#searchFilters.world);
   }

   /**
    * @param {string}   scope - Setting scope; `user` or `world`.
    *
    * @returns {{ itemContext: ItemContext }} The item context loaded into Svelte components.
    */
   static getContext(scope)
   {
      if (scope !== 'user' && scope !== 'world') { throw new Error(`'scope' must be 'user' or 'world'.`); }

      return {
         itemContext: {
            scope,
            canEdit: scope === 'world' ? globalThis.game.user.isGM : true,
            itemGenerator: new ItemGenerator(),
            itemStore: ItemConfiguration.#itemStores[scope],
            maxItems: 25,
            menuItems: new MenuItems(),
            searchFilter: ItemConfiguration.#searchFilters[scope]
         }
      };
   }
}

/**
 * Extends `ObjectEntryStore` which is conveniently exported as `EntryStore`. `ObjectEntryStore` provides a base
 * implementation where only the `set` method and specific data accessors need to be defined. See
 * {@link ItemEntryStore.category} and {@link ItemEntryStore.name}. Calling the protected method
 * `this._updateSubscribers()` will notify ArrayObjectStore to serialize the data to the Foundry DB.
 *
 * This provides the store implementation for serialized {@link ItemEntryData} with accessors
 * for the item properties that update the underlying subscribers.
 *
 * @see https://typhonjs-fvtt-lib.github.io/api-docs/classes/_runtime_svelte_store_reducer_array-object.ObjectEntryStore.html
 *
 * @augments GameSettingArrayObject.EntryStore<ItemEntryData>
 */
export class ItemEntryStore extends GameSettingArrayObject.EntryStore
{
   /**
    * You must define the `set` method.
    *
    * @param {Partial<ItemEntryData>}   data - Item data to set.
    */
   set(data)
   {
      if (typeof data.name === 'string') { this._data.name = data.name; }
      if (typeof data.category === 'string') { this._data.category = data.category; }
   }

   /**
    * @returns {string} Item category.
    */
   get category()
   {
      return this._data.category ?? '';
   }

   /**
    * @param {string} category - Item category.
    */
   set category(category)
   {
      if (typeof category === 'string')
      {
         this._data.category = category;
         this._updateSubscribers();
      }
   }

   /**
    * @returns {string} Item name.
    */
   get name()
   {
      return this._data.name ?? '';
   }

   /**
    * @param {string} name - Item name.
    */
   set name(name)
   {
      if (typeof name === 'string')
      {
         this._data.name = name;
         this._updateSubscribers();
      }
   }
}

/**
 * Automatically initialize and register the item array object stores when Foundry is `ready`.
 */
Hooks.once('ready', () => ItemConfiguration.initialize());

